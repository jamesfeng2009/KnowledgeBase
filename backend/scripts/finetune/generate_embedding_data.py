def _query_variants(query: str) -> list[str]:
    """对原始 query 做同义改写，增加多样性。

    避免模型只学到精确匹配，提升对真实用户多样化提问的泛化能力。
    模拟真实用户提问的多种表达方式（口语化、礼貌用语、省略修饰词等）。
    每个模板可生成 8-10 个变体，82 模板 × 9 ≈ 700+ 条三元组。
    """
    variants = [query]
    plain = query.rstrip("？?。.！!")
    if plain != query:
        variants.append(plain)
    # "怎么" → "如何"
    if query.startswith("怎么"):
        variants.append(query.replace("怎么", "如何", 1))
    # "怎么" → "咋"（口语化）
    if query.startswith("怎么"):
        variants.append(query.replace("怎么", "咋", 1))
    # "请问" 前缀
    variants.append("请问" + plain + "？")
    # "我想知道" 前缀
    variants.append("我想知道" + plain)
    # "麻烦问下" 前缀
    variants.append("麻烦问下" + plain)
    # "呢" 结尾口语化
    if not plain.endswith("呢"):
        variants.append(plain + "呢")
    # 去掉"企业"修饰词
    if "企业" in plain:
        variants.append(plain.replace("企业", ""))
    return list(dict.fromkeys(variants))  # 去重保序


def generate_triplets(count: int = 1000, seed: int = 42) -> list[dict]:
    """生成 (query, pos, neg) 三元组列表。

    策略：每个 QA 模板扩充为多条 query 变体，pos 为正确答案，
    neg 从其他场景的答案中随机抽取（跨场景负例比同场景更难，提升判别力）。
    """
    rng = random.Random(seed)
    triplets: list[dict] = []

    # 按场景分组，便于构造跨场景负例
    by_scene: dict[str, list[tuple[str, str]]] = {}
    for scene, q, a in _QA_TEMPLATES:
        by_scene.setdefault(scene, []).append((q, a))

    scenes = list(by_scene.keys())
    all_answers = [a for _, _, a in _QA_TEMPLATES]

    for scene, query, answer in _QA_TEMPLATES:
        for variant in _query_variants(query):
            if len(triplets) >= count:
                break
            # 负例：70% 跨场景（更难），30% 同场景
            if rng.random() < 0.7:
                other_scenes = [s for s in scenes if s != scene]
                neg_scene = rng.choice(other_scenes)
                neg = rng.choice(by_scene[neg_scene])[1]
            else:
                # 同场景其他问题的答案
                same_scene_answers = [a for q, a in by_scene[scene] if q != query]
                neg = rng.choice(same_scene_answers) if same_scene_answers else rng.choice(all_answers)

            triplets.append({
                "query": variant,
                "pos": answer,
                "neg": neg,
                "meta": {"source": "local_enterprise", "scene": scene},
            })

    rng.shuffle(triplets)
    return triplets[:count]


def write_jsonl(triplets: list[dict], path: str | Path) -> int:
    """写 jsonl 文件，返回写入条数。"""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        for t in triplets:
            f.write(json.dumps(t, ensure_ascii=False) + "\n")
    return len(triplets)


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="本地生成 embedding 微调三元组文件（不依赖网络/数据库）",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    parser.add_argument("--output", default="data/open/embedding.jsonl", help="输出 jsonl 路径")
    parser.add_argument("--count", type=int, default=1000, help="生成条数上限")
    parser.add_argument("--seed", type=int, default=42, help="随机种子（可复现）")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")

    triplets = generate_triplets(count=args.count, seed=args.seed)
    n = write_jsonl(triplets, args.output)

    # 统计
    scenes: dict[str, int] = {}
    for t in triplets:
        s = t["meta"]["scene"]
        scenes[s] = scenes.get(s, 0) + 1

    print(f"\n===== 生成完成 =====")
    print(f"文件: {args.output}")
    print(f"总数: {n} 条三元组")
    print(f"场景分布:")
    for s, c in sorted(scenes.items(), key=lambda x: -x[1]):
        print(f"  {s}: {c} 条 ({c/n*100:.0f}%)")
    print(f"\n下一步:")
    print(f"  1. 看数据画像: python scripts/finetune/data_stats.py {args.output}")
    print(f"  2. 训练: python scripts/finetune/train_embedding.py --data {args.output} --epochs 2")
    return 0


if __name__ == "__main__":
    sys.exit(main())
