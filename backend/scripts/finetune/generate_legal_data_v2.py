    output_path = Path(__file__).resolve().parents[2] / "data" / "open" / "dpo_boundary_patch_v3_legal_ext.jsonl"
    records = [make_pair(q, c, r, s) for q, c, r, s in LEGAL_PAIRS]
    with output_path.open("w", encoding="utf-8") as f:
        for rec in records:
            f.write(json.dumps(rec, ensure_ascii=False) + "\n")

    # 统计
    from collections import Counter
    subcats = Counter(p[3] for p in LEGAL_PAIRS)
    print(f"已生成 {len(records)} 条法律偏好对 → {output_path}")
    print("子领域分布:")
    for sc, n in subcats.most_common():
        print(f"  {sc}: {n}")


